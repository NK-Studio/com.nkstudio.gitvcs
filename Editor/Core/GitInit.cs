        public static bool HasGitignore(string projectRoot)
        {
            return File.Exists(Path.Combine(projectRoot, GitignoreFileName));
        }

        /// <summary>
        /// .gitignore 가 없으면 Unity 용을 쓴다. 이미 있으면 건드리지 않는다.
        /// </summary>
        /// <returns>새로 썼으면 true.</returns>
        public static bool WriteGitignoreIfMissing(string projectRoot)
        {
            string path = Path.Combine(projectRoot, GitignoreFileName);
            if (File.Exists(path))
            {
                return false;
            }
            File.WriteAllText(path, UnityGitignore.Replace("\r\n", "\n"));
            return true;
        }

        /// <summary>
        /// <c>git init</c> 뒤 .gitignore 가 없으면 만든다.
        /// </summary>
        /// <returns>git 결과와, 저장소는 만들었지만 .gitignore 를 못 썼을 때의 까닭(없으면 null).</returns>
        public static async Task<(GitResult result, string gitignoreError)> CreateRepositoryAsync(string projectRoot)
        {
            GitResult result = await GitCommand.RunAsync(projectRoot, new[] { "init" });
            if (result.Success == false)
            {
                return (result, null);
            }
            try
            {
                WriteGitignoreIfMissing(projectRoot);
                return (result, null);
            }
            catch (Exception e) when (e is IOException || e is UnauthorizedAccessException)
            {
                return (result, e.Message);
            }
        }
    }
